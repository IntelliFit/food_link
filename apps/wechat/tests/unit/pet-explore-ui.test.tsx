test('a thrown settlement remains blocked until its dedicated retry succeeds without replaying finish', async () => {
  const callback = jest.fn().mockRejectedValue(new Error('offline'))
  const retry = jest.fn().mockResolvedValue(undefined)
  const { container, rerender } = render(<PetExploreGame {...props} onFinished={callback} />)
  click(container, 'explore-start')
  click(container, 'explore-node-clue')
  click(container, 'explore-observe')
  click(container, 'explore-finish')
  await flush()
  expect(container.querySelector('#explore-continue')).toBeDisabled()
  expect(container.querySelector('#explore-result-exit')).toBeDisabled()
  expect(screen.getByText('收获未保存，请重试保存后再离开。')).toBeInTheDocument()
  rerender(<PetExploreGame {...props} onFinished={callback} onRetrySettlement={retry} />)
  click(container, 'explore-retry-settlement')
  await flush()
  rerender(<PetExploreGame {...props} onFinished={callback} settlementText='已保存' />)
  expect(container.querySelector('#explore-continue')).not.toBeDisabled()
  expect(callback).toHaveBeenCalledTimes(1)
  expect(retry).toHaveBeenCalledTimes(1)
})

test('a local callback failure can retry the captured result and same round even without a parent retry handler', async () => {
  const callback = jest.fn().mockRejectedValueOnce(new Error('offline')).mockResolvedValue(undefined)
  const { container } = render(<PetExploreGame {...props} onFinished={callback} />)
  click(container, 'explore-start')
  click(container, 'explore-node-clue')
  click(container, 'explore-observe')
  click(container, 'explore-finish')
  await flush()
  expect(container.querySelector('#explore-continue')).toBeDisabled()
  expect(container.querySelector('#explore-result-exit')).toBeDisabled()
  expect(container.querySelector('#explore-retry-settlement')).not.toBeDisabled()
  click(container, 'explore-retry-settlement')
  await flush()
  expect(callback).toHaveBeenCalledTimes(2)
  expect(callback.mock.calls[1]).toEqual(callback.mock.calls[0])
  expect(container.querySelector('#explore-continue')).not.toBeDisabled()
})

