test('unmounting a live haul clears its timers and never settles that abandoned round', async () => {
  const callback = jest.fn()
  const { container, unmount } = render(<PetExploreGame {...props} onFinished={callback} />)
  toHaul(container)
  click(container, 'explore-pull-toggle')
  wait(1000)
  expect(jest.getTimerCount()).toBeGreaterThan(0)
  unmount()
  expect(jest.getTimerCount()).toBe(0)
  wait(120000)
  await flush()
  expect(callback).not.toHaveBeenCalled()
})

test('budget exhaustion after a discovered clue settles the real failed trip once and keeps its clue on continuation', async () => {
  const callback = jest.fn()
  const { container } = render(<PetExploreGame {...props} onFinished={callback} />)
  click(container, 'explore-start')
  click(container, 'explore-node-clue')
  click(container, 'explore-observe')
  for (const id of ['camp', 'lookout', 'camp', 'lookout', 'camp', 'lookout', 'camp']) click(container, `explore-node-${id}`)
  await flush()
  expect(callback).toHaveBeenCalledTimes(1)
  expect(callback).toHaveBeenCalledWith(expect.objectContaining({ completed: false, score: 50, stars: 0, detail: expect.objectContaining({ moves: 8, nodes: 1, remaining: 0 }) }), expect.any(String), 'account-one')
  click(container, 'explore-continue')
  expect(container.querySelector('#explore-world')).toHaveAttribute('data-remaining', '8')
  expect(screen.getByText(/1\. 浅滩石牌/)).toBeInTheDocument()
  click(container, 'explore-node-clue')
  click(container, 'explore-observe')
  expect(container.querySelector('#explore-world')).toHaveAttribute('data-score', '0')
})
