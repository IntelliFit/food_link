#!/usr/bin/env node
// Vendor the lifespan-predictor engine constants and golden vectors into the mini program.
// usage: node scripts/sync-lifespan-engine.mjs <dir with constants.json and fixtures.json>
// The constants become a TS module in the packageLifespan subpackage; fixtures.json is test-only.

import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const source = process.argv[2]
if (!source) {
  console.error('usage: node scripts/sync-lifespan-engine.mjs <golden dir>')
  process.exit(1)
}

const read = (name) => JSON.parse(fs.readFileSync(path.join(source, name), 'utf8'))
const constants = read('constants.json')
const fixtures = read('fixtures.json')
if (constants.engine_version !== fixtures.engine_version) {
  console.error(`engine versions differ: ${constants.engine_version} vs ${fixtures.engine_version}`)
  process.exit(1)
}

const header = '// Generated by scripts/sync-lifespan-engine.mjs from lifespan-predictor golden/constants.json. Do not edit.\n'
const targets = [
  ['apps/wechat/src/packageLifespan/engine/constants.ts', `${header}export const ENGINE_CONSTANTS = ${JSON.stringify(constants)}\n`],
  ['apps/wechat/tests/fixtures/lifespan-golden.json', `${JSON.stringify(fixtures)}\n`],
]
for (const [rel, text] of targets) {
  const file = path.join(root, rel)
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, text)
  console.log(`${rel}: ${fs.statSync(file).size} bytes`)
}
console.log(`engine ${constants.engine_version}, registry ${constants.registry_version}, ${fixtures.cases.length} fixtures`)
